import { Router } from 'express';
import authRoutes from './auth.routes';
import userRoutes from './user.routes';
import memberRoutes from './member.routes';
import planRoutes from './plan.routes';
import membershipRoutes from './membership.routes';
import qrRoutes from './qr.routes';
import faceRoutes from './face.routes';
import attendanceRoutes from './attendance.routes';
import trainerRoutes from './trainer.routes';
import paymentRoutes from './payment.routes';
import dashboardRoutes from './dashboard.routes';
import notificationRoutes from './notification.routes';
import reportRoutes from './report.routes';
import deviceRoutes from './device.routes';
import portalRoutes from './portal.routes';
import auditRoutes from './audit.routes';

const api = Router();
api.get('/health', (_req, res) => res.json({ success: true, status: 'ok', time: new Date().toISOString() }));
api.use('/auth', authRoutes);
api.use('/users', userRoutes);
api.use('/members', memberRoutes);
api.use('/plans', planRoutes);
api.use('/memberships', membershipRoutes);
api.use('/qr', qrRoutes);
api.use('/face', faceRoutes);
api.use('/attendance', attendanceRoutes);
api.use('/trainers', trainerRoutes);
api.use('/payments', paymentRoutes);
api.use('/dashboard', dashboardRoutes);
api.use('/notifications', notificationRoutes);
api.use('/reports', reportRoutes);
api.use('/devices', deviceRoutes);
api.use('/me', portalRoutes);
api.use('/audit-logs', auditRoutes);
export default api;
